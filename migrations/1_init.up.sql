CREATE TABLE IF NOT EXISTS users(
    user_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    login VARCHAR(64) NOT NULL UNIQUE,
    password VARCHAR(128) NOT NULL,
    created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS credentials(
    credentials_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    login VARCHAR(64) NOT NULL,
    password VARCHAR(128) NOT NULL,
    user_id INTEGER,
    created_at TIMESTAMP DEFAULT NOW(),
    meta TEXT,

    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS text_data(
    text_data_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    text TEXT NOT NULL,
    user_id INTEGER,
    created_at TIMESTAMP DEFAULT NOW(),
    meta TEXT,

    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS binaries_data(
    binaries_data_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    binary_data BYTEA,
    user_id INTEGER,
    created_at TIMESTAMP DEFAULT NOW(),
    meta TEXT,

    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS bank_cards(
    bank_cards_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    card_number VARCHAR(16) NOT NULL UNIQUE,
    holder VARCHAR(64) NOT NULL,
    cvc VARCHAR(3) NOT NULL,
    expiration_date TIMESTAMP,
    user_id INTEGER,
    created_at TIMESTAMP DEFAULT NOW(),
    meta TEXT,

    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
